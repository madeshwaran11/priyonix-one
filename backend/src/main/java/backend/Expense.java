package backend;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;

import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.mapping.Document;

/**
 * Business expense stored in the MongoDB collection "expenses".
 *
 * Every expense starts in the PENDING state. Approval / rejection is an
 * administrative action performed through a dedicated endpoint (see
 * {@link SecurityConfig} and {@link ExpenseService}) so the approval trail is
 * explicit and role-checked.
 */
@Document(collection = "expenses")
public class Expense {

    @Id
    private String id;

    private String title;

    /** TRAVEL | EQUIPMENT | SOFTWARE | OFFICE | MARKETING | UTILITIES | SALARY | CONSULTING | OTHER */
    private String category;

    private BigDecimal amount;
    private LocalDate expenseDate;
    private String vendor;

    /** CASH | BANK_TRANSFER | CARD | UPI | CHEQUE | OTHER */
    private String paymentMethod;

    private String receiptReference;
    private String notes;

    /** PENDING | APPROVED | REJECTED | REIMBURSED */
    private String status;

    /** Email of the administrator who approved/rejected the expense. */
    private String approvedBy;
    private Instant approvedAt;

    /** Email of the authenticated user who created the expense. */
    private String createdBy;

    private Instant createdAt;
    private Instant updatedAt;

    public Expense() {
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public void setAmount(BigDecimal amount) {
        this.amount = amount;
    }

    public LocalDate getExpenseDate() {
        return expenseDate;
    }

    public void setExpenseDate(LocalDate expenseDate) {
        this.expenseDate = expenseDate;
    }

    public String getVendor() {
        return vendor;
    }

    public void setVendor(String vendor) {
        this.vendor = vendor;
    }

    public String getPaymentMethod() {
        return paymentMethod;
    }

    public void setPaymentMethod(String paymentMethod) {
        this.paymentMethod = paymentMethod;
    }

    public String getReceiptReference() {
        return receiptReference;
    }

    public void setReceiptReference(String receiptReference) {
        this.receiptReference = receiptReference;
    }

    public String getNotes() {
        return notes;
    }

    public void setNotes(String notes) {
        this.notes = notes;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getApprovedBy() {
        return approvedBy;
    }

    public void setApprovedBy(String approvedBy) {
        this.approvedBy = approvedBy;
    }

    public Instant getApprovedAt() {
        return approvedAt;
    }

    public void setApprovedAt(Instant approvedAt) {
        this.approvedAt = approvedAt;
    }

    public String getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(String createdBy) {
        this.createdBy = createdBy;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }
}
